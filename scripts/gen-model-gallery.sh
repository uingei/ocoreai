#!/usr/bin/env bash
# gen-model-gallery.sh. Render the measured gallery from a live server, or fail naming why.
#
# ### Why
# `/v1/models` publishes per-checkpoint verdicts measured in that process (`parsed` /
# `prose_only` / `not_observed`, `honored` / `template_ignores` / `not_observed`, video
# evidence). The leaders advertise model support as adjectives, so the measured table IS the
# differentiator (adoption-runbook § The proof surface). The committed artefacts (models.json +
# the README block between the gallery markers) are copies of one GET, and a copy without a
# refresh command rots. This script is the refresh command; the README prints it beside the
# table, and `ModelGallerySyncTests` goes red when the two committed copies drift from each
# other or a verdict leaves the closed wire vocabulary.
#
# ### What it promises and refuses
# It copies verdicts verbatim. It measures nothing itself, so it can never publish a row the
# server did not measure. An empty `data` is a refusal with a cause (a booted-but-unmeasured
# server renders zero rows), never an empty authoritative-looking gallery.
#
# Usage: bash scripts/gen-model-gallery.sh [BASE_URL]   (default http://127.0.0.1:8080)
set -euo pipefail

BASE="${1:-http://127.0.0.1:8080}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BODY="$(mktemp -t gallery-models-XXXXXX)"
trap 'rm -f "$BODY"' EXIT

if ! curl -sf --max-time 15 "$BASE/v1/models" -o "$BODY"; then
  echo "gen-model-gallery: GET $BASE/v1/models failed — is a server up? boot one (probes' recipe:" >&2
  echo "  OCOREAI_ENABLE_HTTP=1 OCOREAI_HOST=127.0.0.1 OCOREAI_PORT=8080 <bin> serve < /dev/null &)" >&2
  exit 1
fi

python3 - "$BODY" "$ROOT/models.json" "$ROOT/README.md" <<'PY'
import json, sys, datetime

body, models_path, readme_path = sys.argv[1], sys.argv[2], sys.argv[3]
data = json.load(open(body)).get("data") or []
ready = [r for r in data if not r.get("loadProgress")]
if not ready:
    sys.exit("gen-model-gallery: the server published 0 ready rows — refusing to write an "
             "empty gallery; load/measure at least one checkpoint first")

# The wire's own keys, projected verbatim; absent stays absent, inferred never rides.
KEYS = ["id", "max_model_len", "vlm", "capabilities",
        "toolCallDelivery", "toolCallEvidence",
        "reasoningEffort", "videoInput", "videoEvidence"]
models = [{k: r[k] for k in KEYS if k in r} for r in ready]
models.sort(key=lambda m: m["id"])
doc = {"schema": "ocoreai-gallery/1",
       "generatedAt": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
       "source": "GET /v1/models",
       "models": models}
with open(models_path, "w") as f:
    json.dump(doc, f, indent=2, ensure_ascii=False)
    f.write("\n")

def cell(m, k):
    return str(m.get(k, "—"))

header = "| model | vlm | context | tool calls | reasoning_effort | video |\n|---|---|---|---|---|---|"
rows = [f"| `{cell(m,'id')}` | {cell(m,'vlm')} | {cell(m,'max_model_len')} | "
        f"{cell(m,'toolCallDelivery')} | {cell(m,'reasoningEffort')} | {cell(m,'videoInput')} |"
        for m in models]
block = "\n".join([
    "<!-- gallery:start — generated by scripts/gen-model-gallery.sh; ModelGallerySyncTests",
    "goes red if README and models.json drift. Refresh against a measured server:",
    "`bash scripts/gen-model-gallery.sh http://127.0.0.1:8080` -->",
    header, *rows,
    "<!-- gallery:end -->"])

text = open(readme_path).read()
start, end = text.find("<!-- gallery:start"), text.find("<!-- gallery:end -->")
if start < 0 or end < 0:
    sys.exit("gen-model-gallery: README.md carries no gallery marker pair — add them once, "
             "in the section where the table belongs")
open(readme_path, "w").write(text[:start] + block + text[end + len("<!-- gallery:end -->"):])
print(f"gen-model-gallery: wrote {len(models)} row(s) -> models.json + README block")
PY
