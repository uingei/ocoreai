#!/usr/bin/env bash
# 42-openapi-contract.sh — is the published OpenAPI document the server, or a description of it?
#
# ### Why
# `GET /openapi.json` renders from `V1EndpointCatalog`, and the committed `openapi.json` is
# `make openapi` over that same render, so both artefacts are generated. What no compile-time test
# can decide is whether the bytes a client actually receives are those artefacts: middleware,
# content type, the 404 envelope and the running process's own version are only visible over a
# socket. Every other tree this repo studies publishes a contract file; the difference here is that
# ours cannot go stale silently, and this probe is the live half of that claim.
#
# ### No weights
# A script drives the engine (`OCOREAI_SCRIPTED_ENGINE`), so the whole verdict is a wire-contract
# verdict at k=1 and runs in the sandbox tier — the same tier probe 37 established. Nothing here
# may be read as a model having done anything (AGENTS.md invariant 2).
#
# ### What is asserted
#   1. It is served: 200, `application/json`, parses, `openapi` is the version the code claims, and
#      the path count has a floor (an empty `paths` would satisfy every subset test below).
#   2. The route set is the catalog: spec paths+methods == `/v1/capabilities` `endpoints[]`
#      percent-for-percent, in both directions.
#   3. The documented envelope is the served envelope: every key the spec marks required on
#      `error` is present on a real 404, with the code and `error_code` it names.
#   4. The document describes the process that served it: `info.version` == the same binary's
#      `--version`, and its route set == the same binary's `--openapi` stdout. A file generated by
#      one build and served by another is the drift this artefact exists to prevent.
#   5. It invents no deployment: `servers[0].url` is `/` and no host or port literal appears —
#      the bind truth lives in the `OCOREAI_PORT` reads, not in the spec.

set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_lib.sh
source "$HERE/_lib.sh"
PROBE_NAME="openapi-contract"

SCRIPT_FILE="$(mktemp -t ocoreai-script-XXXXXX).json"
probe_atexit "rm -f '$SCRIPT_FILE'"
cat > "$SCRIPT_FILE" <<'JSON'
{
  "segments": ["contract probe placeholder."],
  "finishReason": "eos",
  "promptTokens": 4,
  "generatedTokens": 3
}
JSON
export OCOREAI_SCRIPTED_ENGINE="$SCRIPT_FILE"

probe_boot

# ── §1 served, and big enough to mean something ───────────────────────────────────────────
probe_section "§1 the document is served, not just committed"
SPEC_FILE="$(mktemp -t ocoreai-spec-XXXXXX).json"
probe_atexit "rm -f '$SPEC_FILE'"
HTTP_HDR="$(mktemp -t ocoreai-hdr-XXXXXX).txt"
probe_atexit "rm -f '$HTTP_HDR'"
if ! curl -sS -m "${OCOREAI_PROBE_CURL_TIMEOUT:-60}" -D "$HTTP_HDR" -o "$SPEC_FILE" \
    -w '%{http_code}' "$PROBE_BASE/openapi.json" > /dev/null 2>&1; then
  probe_fail "GET /openapi.json did not answer — the route is registered and must be reachable"
  probe_summary "$PROBE_NAME"
fi
CT="$(tr -d '\r' < "$HTTP_HDR" | sed -nE 's/^[Cc]ontent-[Tt]ype: *//p' | head -1)"
if [ "$CT" = "application/json" ]; then
  probe_ok "content type is application/json (not a quoted JSON string)"
else
  probe_fail "content type is '$CT' — a generator decoding the body would get a string, not an object"
fi
if ! python3 -c 'import json,sys; json.load(open(sys.argv[1]))' "$SPEC_FILE" 2>/dev/null; then
  probe_fail "the served body is not parseable JSON — nothing below can be decided"
  probe_summary "$PROBE_NAME"
fi
SPEC_VERSION="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("openapi",""))' "$SPEC_FILE")"
if [ -n "$SPEC_VERSION" ]; then
  probe_ok "openapi=$SPEC_VERSION, and the body parsed"
else
  probe_fail "no \`openapi\` key — this is not a versioned contract"
fi
OP_COUNT="$(python3 -c '
import json, sys
paths = json.load(open(sys.argv[1])).get("paths", {})
verbs = {"get", "post", "patch", "put", "delete"}
print(sum(1 for ops in paths.values() for k in ops if k in verbs))' "$SPEC_FILE")"
probe_require_int "operations in the served document" "$OP_COUNT"
if [ "${OP_COUNT:-0}" -ge 30 ]; then
  probe_ok "$OP_COUNT operations in the served document — the floor a vacuous scan would undercut"
else
  probe_fail "only $OP_COUNT operations served — paths silently dropped from the render"
fi

# ── §2 the served route set is the published index ────────────────────────────────────────
probe_section "§2 spec paths+methods == /v1/capabilities endpoints[]"
probe_api GET /v1/capabilities
if [ "${PROBE_STATUS:-}" != "200" ]; then
  probe_fail "GET /v1/capabilities -> ${PROBE_STATUS:-no response}; §2 has no index to compare with"
else
  # The body travels by environment, not argv: a /v1/capabilities payload is ~14 KB and argv
  # refuses it ("File name too long", measured on this probe's first run).
  DIFF="$(CAP_BODY="$PROBE_BODY" python3 - "$SPEC_FILE" <<'PY'
import json, os, sys
spec = json.load(open(sys.argv[1]))
lines = json.loads(os.environ["CAP_BODY"]).get("endpoints", [])
verbs = {"get", "post", "patch", "put", "delete"}

def templated(p):
    return "/" + "/".join(
        "{" + seg[1:] + "}" if seg.startswith(":") else seg
        for seg in p.strip("/").split("/"))

served = {(m.upper(), templated(p)) for m, p in ((e["method"], e["path"]) for e in lines)}
documented = {
    (k.upper(), p) for p, ops in spec.get("paths", {}).items() for k in ops if k in verbs
}
if not served or not documented:
    print(f"EMPTY served={len(served)} documented={len(documented)}")
else:
    missing = sorted(f"{m} {p}" for m, p in served - documented)
    extra = sorted(f"{m} {p}" for m, p in documented - served)
    if missing or extra:
        print("DIFF missing=%s extra=%s" % (missing, extra))
    else:
        print("OK %d" % len(served))
PY
    2>&1)"
  # An empty verdict is its own failure: this step's first run printed nothing because the
  # comprehension raised inside a heredoc, and `case` fell through to the "disagree" branch with
  # no detail. Stderr is captured into the verdict for the same reason: a red that names nothing
  # is a red nobody root-causes.
  if [ -z "$DIFF" ]; then
    probe_fail "§2 produced no verdict — the comparison itself died, so it judged nothing"
  else
    case "$DIFF" in
      OK\ *) probe_ok "${DIFF#OK } routes: the index and the contract are the same set" ;;
      EMPTY\ *) probe_fail "§2 compared nothing ($DIFF) — one side of the scan rotted" ;;
      *) probe_fail "the contract and the published index disagree — $DIFF" ;;
    esac
  fi
fi

# ── §3 the documented envelope is the served envelope ─────────────────────────────────────
probe_section "§3 a real 404 carries the keys the spec calls required"
REQUIRED="$(python3 -c '
import json, sys
c = json.load(open(sys.argv[1])).get("components", {})
err = c.get("schemas", {}).get("ErrorEnvelope", {}).get("properties", {}).get("error", {})
print(",".join(err.get("required", [])))' "$SPEC_FILE")"
if [ -z "$REQUIRED" ]; then
  probe_fail "the spec stopped marking ErrorEnvelope.error as required — the envelope has no contract"
else
  probe_ok "spec requires: $REQUIRED"
  probe_api GET /v1/definitely-not-a-route-42
  if [ "${PROBE_STATUS:-}" != "404" ]; then
    probe_fail "an unknown path answered ${PROBE_STATUS:-nothing}, expected 404"
  else
    MISS="$(ERR_BODY="$PROBE_BODY" python3 - "$SPEC_FILE" <<'PY'
import json, os, sys
required = json.load(open(sys.argv[1]))["components"]["schemas"]["ErrorEnvelope"] \
    ["properties"]["error"].get("required", [])
body = json.loads(os.environ["ERR_BODY"])
inner = body.get("error")
if not isinstance(inner, dict):
    print("NO-ERROR-KEY keys=%s" % sorted(body)); raise SystemExit
print(",".join(sorted(k for k in required if k not in inner)) or "OK")
PY
)"
    case "$MISS" in
      OK)
        probe_ok "every required key is on the served 404"
        CODE="$(probe_json "$PROBE_BODY" 'error.code')"
        ECODE="$(probe_json "$PROBE_BODY" 'error.error_code')"
        if [ "${CODE:-}" = "404" ] && [ "${ECODE:-}" = "route_not_found" ]; then
          probe_ok "error.code=404 · error_code=route_not_found, as documented"
        else
          probe_fail "error.code=${CODE:-?} · error_code=${ECODE:-?} — the spec describes a different refusal"
        fi
        ;;
      NO-ERROR-KEY*) probe_fail "the 404 body is not an error envelope ($MISS)" ;;
      *) probe_fail "the served 404 is missing documented required keys: $MISS" ;;
    esac
  fi
fi

# ── §4 the document describes the process that served it ──────────────────────────────────
probe_section "§4 version and route set match the binary, not a previous build"
BIN=""
if ! BIN="$(probe_resolve_binary)"; then
  probe_fail "§4 cannot resolve the binary under test — the claim it makes would be unchecked"
else
  CLI_VERSION="$("$BIN" --version 2>/dev/null | awk 'NR==1{print $2}')"
  DOC_VERSION="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["info"]["version"])' "$SPEC_FILE")"
  if [ -n "$CLI_VERSION" ] && [ "$CLI_VERSION" = "$DOC_VERSION" ]; then
    probe_ok "info.version=$DOC_VERSION is this binary's own --version"
  else
    probe_fail "served doc says version '${DOC_VERSION:-?}' but the same binary says --version '${CLI_VERSION:-?}'" \
      "— the document would be describing a build that is not running"
  fi
  CLI_SET="$("$BIN" --openapi 2>/dev/null \
    | python3 -c '
import json, sys
verbs = {"get", "post", "patch", "put", "delete"}
print(sorted(f"{k.upper()} {p}" for p, ops in json.load(sys.stdin)["paths"].items() for k in ops if k in verbs))')"
  DOC_SET="$(python3 -c '
import json, sys
verbs = {"get", "post", "patch", "put", "delete"}
print(sorted(f"{k.upper()} {p}" for p, ops in json.load(open(sys.argv[1]))["paths"].items() for k in ops if k in verbs))' "$SPEC_FILE")"
  if [ -n "$CLI_SET" ] && [ "$CLI_SET" = "$DOC_SET" ]; then
    probe_ok "the CLI render and the served render carry the same route set"
  else
    probe_fail "the binary's --openapi render and the served document disagree on routes" \
      "— one of them is not coming from V1EndpointCatalog"
  fi
fi

# ── §5 no invented deployment ─────────────────────────────────────────────────────────────
probe_section "§5 the contract binds no host and no port"
URL0="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("servers",[{}])[0].get("url",""))' "$SPEC_FILE")"
if [ "$URL0" = "/" ]; then
  probe_ok "servers[0].url is / — the origin that served this document, the only one it can vouch for"
else
  probe_fail "servers[0].url is '$URL0' — a hardcoded origin is a fifth home for OCOREAI_HOST/OCOREAI_PORT"
fi
for forbidden in "127.0.0.1" "localhost" ":8080"; do
  if grep -q -- "$forbidden" "$SPEC_FILE"; then
    probe_fail "the served contract contains '$forbidden' — the bind truth belongs to the env reads"
  else
    probe_ok "no '$forbidden' literal in the contract"
  fi
done

probe_summary "$PROBE_NAME"
